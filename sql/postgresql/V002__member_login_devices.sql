CREATE TABLE member_login_devices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    device_id character varying(64) NOT NULL,
    platform character varying(32),
    device_name character varying(128),
    device_model character varying(128),
    os_version character varying(64),
    app_version character varying(64),
    first_login_ip character varying(64),
    last_login_ip character varying(64),
    first_login_at bigint NOT NULL,
    last_login_at bigint NOT NULL,
    login_count bigint DEFAULT 1 NOT NULL,
    created_at bigint NOT NULL,
    updated_at bigint NOT NULL,
    CONSTRAINT member_login_devices_user_device_uq UNIQUE (user_id, device_id)
);

CREATE INDEX member_login_devices_user_last_login_idx
    ON member_login_devices (user_id, last_login_at DESC);

COMMENT ON TABLE member_login_devices IS '会员登录设备审计；不保存 access/refresh token';
COMMENT ON COLUMN member_login_devices.first_login_ip IS '首次登录时由服务端连接信息确定的 IP';
COMMENT ON COLUMN member_login_devices.last_login_ip IS '最近登录时由服务端连接信息确定的 IP';
