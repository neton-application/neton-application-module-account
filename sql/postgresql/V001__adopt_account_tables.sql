-- =============================================================================
-- account V001：接管账号表
--
-- 账号能力从 member 模块拆出（member 只留会员成长）。表的归属同时转移：
--
--   存量库：这些表由 member 的 V001–V003 建出 → 原地改名。改名只动元数据，瞬间完成，
--           不复制数据；用户 id 不变，所以已签发的 token（sub = 用户 id）照常有效。
--   全新安装：account 在拓扑序上先于 member，此时这些表还不存在 → 按终态结构建表。
--             之后 member 的 V001 仍会建一份旧名的空表（它的已执行脚本有校验和，不能改），
--             由 member 的 V004 负责清理。
--
-- `account_users` 上的成长字段（level_id / experience / point / group_id）这里**不动**：
-- 迁移按模块拓扑序整体执行，account 的脚本全部跑完 member 才开始，若在这里删列，
-- member 还没来得及把数据复制走。复制与删列都放在 member 的 V004。
-- =============================================================================
SET search_path = public;

-- ── 1. 存量库：改名 ─────────────────────────────────────────────────────────
DO $$
BEGIN
    IF to_regclass('public.member_users') IS NOT NULL AND to_regclass('public.account_users') IS NULL THEN
        ALTER TABLE member_users RENAME TO account_users;
        ALTER SEQUENCE IF EXISTS member_users_id_seq RENAME TO account_users_id_seq;
        IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'member_users_pkey') THEN
            ALTER TABLE account_users RENAME CONSTRAINT member_users_pkey TO account_users_pkey;
        END IF;
        ALTER INDEX IF EXISTS uq_member_users_username RENAME TO uq_account_users_username;
        ALTER INDEX IF EXISTS uq_member_users_mobile   RENAME TO uq_account_users_mobile;
        ALTER INDEX IF EXISTS uq_member_users_email    RENAME TO uq_account_users_email;
        ALTER INDEX IF EXISTS idx_member_users_is_robot RENAME TO idx_account_users_is_robot;
        ALTER INDEX IF EXISTS idx_member_users_mobile   RENAME TO idx_account_users_mobile;
        ALTER INDEX IF EXISTS idx_member_users_guest    RENAME TO idx_account_users_guest;
    END IF;

    IF to_regclass('public.member_login_devices') IS NOT NULL AND to_regclass('public.account_login_devices') IS NULL THEN
        ALTER TABLE member_login_devices RENAME TO account_login_devices;
        ALTER SEQUENCE IF EXISTS member_login_devices_id_seq RENAME TO account_login_devices_id_seq;
        IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'member_login_devices_pkey') THEN
            ALTER TABLE account_login_devices RENAME CONSTRAINT member_login_devices_pkey TO account_login_devices_pkey;
        END IF;
        IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'member_login_devices_user_device_uq') THEN
            ALTER TABLE account_login_devices RENAME CONSTRAINT member_login_devices_user_device_uq TO account_login_devices_user_device_uq;
        END IF;
        ALTER INDEX IF EXISTS member_login_devices_user_last_login_idx RENAME TO account_login_devices_user_last_login_idx;
    END IF;

    IF to_regclass('public.member_nickname_adjective') IS NOT NULL AND to_regclass('public.account_nickname_adjective') IS NULL THEN
        ALTER TABLE member_nickname_adjective RENAME TO account_nickname_adjective;
        ALTER SEQUENCE IF EXISTS member_nickname_adjective_id_seq RENAME TO account_nickname_adjective_id_seq;
        IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'member_nickname_adjective_pkey') THEN
            ALTER TABLE account_nickname_adjective RENAME CONSTRAINT member_nickname_adjective_pkey TO account_nickname_adjective_pkey;
        END IF;
        IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'member_nickname_adjective_word_key') THEN
            ALTER TABLE account_nickname_adjective RENAME CONSTRAINT member_nickname_adjective_word_key TO account_nickname_adjective_word_key;
        END IF;
        ALTER INDEX IF EXISTS idx_member_nickname_adjective_status RENAME TO idx_account_nickname_adjective_status;
    END IF;

    IF to_regclass('public.member_nickname_noun') IS NOT NULL AND to_regclass('public.account_nickname_noun') IS NULL THEN
        ALTER TABLE member_nickname_noun RENAME TO account_nickname_noun;
        ALTER SEQUENCE IF EXISTS member_nickname_noun_id_seq RENAME TO account_nickname_noun_id_seq;
        IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'member_nickname_noun_pkey') THEN
            ALTER TABLE account_nickname_noun RENAME CONSTRAINT member_nickname_noun_pkey TO account_nickname_noun_pkey;
        END IF;
        IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'member_nickname_noun_word_key') THEN
            ALTER TABLE account_nickname_noun RENAME CONSTRAINT member_nickname_noun_word_key TO account_nickname_noun_word_key;
        END IF;
        ALTER INDEX IF EXISTS idx_member_nickname_noun_status RENAME TO idx_account_nickname_noun_status;
    END IF;
END $$;

-- ── 2. 全新安装：按终态建表（存量库上全部是 no-op）─────────────────────────────
CREATE TABLE IF NOT EXISTS account_users (
    id                  bigint NOT NULL,
    identity_provider   character varying(32) DEFAULT 'builtin'::character varying NOT NULL,
    mobile              character varying(20),
    email               character varying(255),
    password            character varying(255),
    nickname            character varying(64) DEFAULT ''::character varying NOT NULL,
    avatar              character varying(512),
    status              smallint DEFAULT 0 NOT NULL,
    register_ip         character varying(64),
    login_ip            character varying(64),
    login_date          bigint,
    username            character varying(64),
    username_updated_at bigint,
    gender              smallint DEFAULT 0 NOT NULL,
    bio                 character varying(200),
    birthday            character varying(10),
    is_robot            smallint DEFAULT 0 NOT NULL,
    is_guest            smallint DEFAULT 0 NOT NULL,
    session_version     bigint DEFAULT 0 NOT NULL,
    current_device_id   character varying(64),
    deleted             smallint DEFAULT 0 NOT NULL,
    created_at          bigint DEFAULT 0 NOT NULL,
    updated_at          bigint DEFAULT 0 NOT NULL,
    CONSTRAINT account_users_pkey PRIMARY KEY (id)
);
-- 账号 id 由代码取号（BuiltinAccountIdentityAdapter），起点 10000 与改造前一致。
CREATE SEQUENCE IF NOT EXISTS account_users_id_seq AS bigint START WITH 10000 INCREMENT BY 1;
CREATE UNIQUE INDEX IF NOT EXISTS uq_account_users_username ON account_users (username);
CREATE UNIQUE INDEX IF NOT EXISTS uq_account_users_mobile ON account_users (mobile) WHERE mobile IS NOT NULL AND mobile <> '';
CREATE UNIQUE INDEX IF NOT EXISTS uq_account_users_email ON account_users (email) WHERE email IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_account_users_is_robot ON account_users (is_robot);
CREATE INDEX IF NOT EXISTS idx_account_users_mobile ON account_users (mobile);
CREATE INDEX IF NOT EXISTS idx_account_users_guest ON account_users (is_guest) WHERE is_guest = 1;

CREATE TABLE IF NOT EXISTS account_login_devices (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        bigint NOT NULL,
    device_id      character varying(64) NOT NULL,
    platform       character varying(32),
    device_name    character varying(128),
    device_model   character varying(128),
    os_version     character varying(64),
    app_version    character varying(64),
    first_login_ip character varying(64),
    last_login_ip  character varying(64),
    first_login_at bigint NOT NULL,
    last_login_at  bigint NOT NULL,
    login_count    bigint DEFAULT 1 NOT NULL,
    created_at     bigint NOT NULL,
    updated_at     bigint NOT NULL,
    CONSTRAINT account_login_devices_user_device_uq UNIQUE (user_id, device_id)
);
CREATE INDEX IF NOT EXISTS account_login_devices_user_last_login_idx ON account_login_devices (user_id, last_login_at DESC);

CREATE TABLE IF NOT EXISTS account_nickname_adjective (
    id         bigserial PRIMARY KEY,
    word       character varying(32) NOT NULL UNIQUE,
    status     smallint DEFAULT 1 NOT NULL,
    created_at bigint DEFAULT 0 NOT NULL,
    updated_at bigint DEFAULT 0 NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_account_nickname_adjective_status ON account_nickname_adjective (status);

CREATE TABLE IF NOT EXISTS account_nickname_noun (
    id         bigserial PRIMARY KEY,
    word       character varying(32) NOT NULL UNIQUE,
    status     smallint DEFAULT 1 NOT NULL,
    created_at bigint DEFAULT 0 NOT NULL,
    updated_at bigint DEFAULT 0 NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_account_nickname_noun_status ON account_nickname_noun (status);

-- 举报。model 一直映射这张表，但改造前**从没有任何迁移建过它** —— 举报接口一调就因表不存在报错。
CREATE TABLE IF NOT EXISTS account_reports (
    id                  bigserial PRIMARY KEY,
    reporter_uid        bigint NOT NULL,
    target_type         character varying(32) NOT NULL,
    target_id           character varying(64) NOT NULL,
    reported_uid        bigint,
    reason              integer NOT NULL,
    description         text,
    evidence_message_id bigint,
    status              smallint DEFAULT 0 NOT NULL,
    deleted             smallint DEFAULT 0 NOT NULL,
    created_at          bigint,
    updated_at          bigint
);
CREATE INDEX IF NOT EXISTS idx_account_reports_status ON account_reports (status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_account_reports_reported ON account_reports (reported_uid);

