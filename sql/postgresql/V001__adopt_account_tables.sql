-- 5.4 授权
-- 超管：账号中心下全部。
INSERT INTO system_role_menus (role_id, menu_id, created_at)
SELECT r.id, m.id, (extract(epoch from now()) * 1000)::bigint
FROM system_roles r
JOIN system_menus m ON (m.type = 1 AND m.parent_id = 0 AND m.path = '/account')
                    OR m.permission IN ('account:user:query', 'account:user:update', 'account:user:update-password',
                                        'account:nickname:query', 'account:nickname:create',
                                        'account:nickname:update', 'account:nickname:delete')
WHERE r.code IN ('super_admin')
  -- system_role_menus 只有 id 主键、没有 (role_id, menu_id) 唯一约束，ON CONFLICT 拦不住重复，
  -- 只能显式判存在。
  AND NOT EXISTS (SELECT 1 FROM system_role_menus x WHERE x.role_id = r.id AND x.menu_id = m.id);
-- 其他角色：凡是原来能看「会员列表」的，补上新目录，否则菜单树里子节点没有父节点、整组不显示。
INSERT INTO system_role_menus (role_id, menu_id, created_at)
SELECT DISTINCT rm.role_id, d.id, (extract(epoch from now()) * 1000)::bigint
FROM system_role_menus rm
JOIN system_menus p ON p.id = rm.menu_id AND p.permission = 'account:user:query'
CROSS JOIN (SELECT id FROM system_menus WHERE type = 1 AND parent_id = 0 AND path = '/account' ORDER BY id LIMIT 1) d
WHERE NOT EXISTS (SELECT 1 FROM system_role_menus x WHERE x.role_id = rm.role_id AND x.menu_id = d.id);
