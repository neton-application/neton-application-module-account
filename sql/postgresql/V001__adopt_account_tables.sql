-- 5.3 全新安装：新建账号列表与按钮
WITH dir AS (
    SELECT id FROM system_menus WHERE type = 1 AND parent_id = 0 AND path = '/account' ORDER BY id LIMIT 1
),
page AS (
    INSERT INTO system_menus (name, permission, type, parent_id, path, component, icon, sort, status, created_at, updated_at)
    SELECT '账号列表', 'account:user:query', 2, dir.id, 'user', 'account/user/index', 'ant-design:user-outlined', 1, 1,
           (extract(epoch from now()) * 1000)::bigint, (extract(epoch from now()) * 1000)::bigint
    FROM dir
    WHERE NOT EXISTS (SELECT 1 FROM system_menus WHERE permission = 'account:user:query')
    RETURNING id
),
parent AS (
    SELECT id FROM page
    UNION ALL
    SELECT id FROM system_menus WHERE permission = 'account:user:query' AND type = 2
)
INSERT INTO system_menus (name, permission, type, parent_id, path, component, icon, sort, status, created_at, updated_at)
SELECT v.name, v.permission, 3, (SELECT id FROM parent LIMIT 1), NULL, NULL, NULL, v.sort, 1,
       (extract(epoch from now()) * 1000)::bigint, (extract(epoch from now()) * 1000)::bigint
FROM (VALUES
    ('账号修改',     'account:user:update',          1),
    ('昵称词库查询', 'account:nickname:query',       3),
    ('新增昵称词条', 'account:nickname:create',      4),
